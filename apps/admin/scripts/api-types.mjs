#!/usr/bin/env node
/**
 * Generate TypeScript types for the admin from the API contract (apps/api/openapi.json).
 *   npm run api:types -w @soltex/admin            write src/lib/api/schema.gen.ts
 *   npm run api:types -w @soltex/admin -- --check  fail if the committed file is out of date (CI)
 *
 * The OpenAPI document is the single contract between the API and the admin (approved review §D:
 * "typed client for the admin"). It is read as a file; the admin never imports API code.
 * Supports exactly the JSON Schema subset the API emits (object, array, enum, const, nullable
 * type lists, anyOf, $ref, records); anything else fails loudly instead of degrading to `any`.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE = path.resolve(ROOT, '../api/openapi.json');
const TARGET = path.join(ROOT, 'src/lib/api/schema.gen.ts');

const doc = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
const prop = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
const ind = (s, n) => s.replace(/\n/g, `\n${'  '.repeat(n)}`);

function ts(schema, where) {
  if (!schema || Object.keys(schema).length === 0) return 'unknown';
  if (schema.$ref) return schema.$ref.replace('#/components/schemas/', '');
  if (schema.anyOf) return [...new Set(schema.anyOf.map((s) => ts(s, where)))].join(' | ');
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  if ('const' in schema) return JSON.stringify(schema.const);
  if (Array.isArray(schema.type)) return schema.type.map((t) => ts({ ...schema, type: t }, where)).join(' | ');
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `Array<${ts(schema.items, where)}>`;
    case 'object': {
      if (!schema.properties) return 'Record<string, unknown>';
      const req = new Set(schema.required ?? []);
      const lines = Object.entries(schema.properties).map(([k, v]) => {
        const doc = v.description ? `/** ${v.description.replace(/\*\//g, '* /')} */\n` : '';
        return `${doc}${prop(k)}${req.has(k) ? '' : '?'}: ${ind(ts(v, `${where}.${k}`), 0)};`;
      });
      return `{\n  ${ind(lines.join('\n'), 1)}\n}`;
    }
  }
  throw new Error(`api-types: unsupported schema at ${where}: ${JSON.stringify(schema).slice(0, 200)}`);
}

const out = [
  '/* eslint-disable */',
  '// GENERATED by apps/admin/scripts/api-types.mjs from apps/api/openapi.json. Do not edit by hand.',
  `// API ${doc.info.title} ${doc.info.version} (OpenAPI ${doc.openapi}).`,
  '',
];

// Component schemas (output variants only; "…Input" duplicates are the request-side twins).
for (const [name, schema] of Object.entries(doc.components?.schemas ?? {})) {
  if (name.endsWith('Input')) continue;
  out.push(`export type ${name} = ${ts(schema, name)};`, '');
}

// Operations: request body, query, path params and the success response.
const ops = [];
for (const [p, methods] of Object.entries(doc.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    const key = `${method.toUpperCase()} ${p}`;
    const body = op.requestBody?.content?.['application/json']?.schema;
    const okEntry = Object.entries(op.responses).find(([c]) => Number(c) >= 200 && Number(c) < 300);
    const ok = okEntry?.[1]?.content?.['application/json']?.schema;
    const params = (op.parameters ?? []).filter((x) => x.in === 'query' || x.in === 'path');
    const query = params.filter((x) => x.in === 'query');
    const pathP = params.filter((x) => x.in === 'path');
    const obj = (list) => `{ ${list.map((x) => `${prop(x.name)}${x.required ? '' : '?'}: ${ts(x.schema, `${key}.${x.name}`)};`).join(' ')} }`;
    ops.push(
      `  ${JSON.stringify(key)}: {\n` +
        `    body: ${body ? ind(ts(body, `${key}.body`), 2) : 'never'};\n` +
        `    query: ${query.length ? obj(query) : 'never'};\n` +
        `    params: ${pathP.length ? obj(pathP) : 'never'};\n` +
        `    response: ${ok === undefined || ok?.type === 'null' ? 'void' : ind(ts(ok, `${key}.response`), 2)};\n` +
        `    status: ${okEntry ? Number(okEntry[0]) : 200};\n` +
        `  };`
    );
  }
}
out.push('export interface Operations {', ...ops, '}', '', 'export type OperationKey = keyof Operations;', '');

const text = out.join('\n');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (current !== text) {
    console.error('api-types: src/lib/api/schema.gen.ts is out of date. Run `npm run api:types -w @soltex/admin` and commit.');
    process.exit(1);
  }
  console.log('api-types: up to date');
} else {
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, text);
  console.log(`api-types: wrote ${path.relative(process.cwd(), TARGET)} (${ops.length} operations)`);
}
